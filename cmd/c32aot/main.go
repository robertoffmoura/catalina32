// Command c32aot compiles hot guest functions of an i386 Mach-O executable ahead of time into Go
// code that runs on the catalina32 CPU state.
//
//	go run ./cmd/c32aot -game <exe> -funcs 0x0007ab10,0x0029ce40 -pkg lswsaga -out pkg/games/lswsaga/aot_gen.go
//
// Each guest function becomes one Go function, registered as an intercept at every basic block
// start, that executes whole blocks natively. Exactness rules (so compiled and interpreted runs
// produce identical traces):
//   - every executed guest instruction adds one to CPU.Steps, and a block only runs if it fits
//     before CPU.EventStep() (otherwise one instruction is interpreted with StepRaw);
//   - instructions the generator does not translate (and calls, returns, indirect jumps) run in
//     place through CPU.StepRaw; if they leave the block's straight-line path, control returns
//     to the interpreter, which re-enters compiled code at the next registered block start;
//   - flags are only computed when a later instruction of the same block may read them (all
//     flags are assumed live at block ends).
//
// The executable is read from disk: functions patched in memory at runtime must not be listed.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/arch/x86/x86asm"

	"catalina32/pkg/macho32"
)

type inst struct {
	pc   uint32
	in   x86asm.Inst
	next uint32
	kind int // kNative, kRaw, kBranch, kJmp
	// flagsDead: this instruction's flag results are never read.
	flagsDead bool
}

const (
	kNative = iota
	kRaw
	kBranch // Jcc rel
	kJmp    // JMP rel
	kCall   // CALL rel: push the return address and leave (the callee runs outside)
	kRet    // RET: return to the caller and leave
)

func main() {
	game := flag.String("game", "", "i386 Mach-O executable")
	funcs := flag.String("funcs", "", "comma-separated function start addresses")
	pkg := flag.String("pkg", "main", "Go package name")
	out := flag.String("out", "", "output .go file")
	flag.Parse()
	img, err := macho32.LoadImage(*game)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	mem := make([]byte, 0x04000000)
	if err := img.MapIntoArena(mem); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by c32aot; DO NOT EDIT.\n\npackage %s\n\nimport (\n\t\"fmt\"\n\t\"math\"\n\n\t\"catalina32/pkg/cpu\"\n)\n\nvar _ = math.Trunc // not every translation uses math\n\n", *pkg)
	type reg struct {
		name     string
		entries  []uint32
		lo, hi   uint32
		codeHash uint64
	}
	var regs []reg
	stats := map[string]int{}
	for _, f := range strings.Split(*funcs, ",") {
		a, err := strconv.ParseUint(strings.TrimSpace(f), 0, 32)
		if err != nil {
			continue
		}
		size, ok := img.FDEs[uint32(a)]
		if !ok {
			// No unwind info (e.g. statically linked C libraries): find the body by following
			// control flow, bounded by the next known function start.
			if size = flowExtent(mem, uint32(a), nextFuncStart(img, uint32(a))); size == 0 {
				fmt.Fprintf(os.Stderr, "0x%08x: no FDE and no decodable body, skipped\n", a)
				continue
			}
			fmt.Fprintf(os.Stderr, "0x%08x: no FDE, %d bytes by control flow\n", a, size)
		}
		name := fmt.Sprintf("aot_%08x", a)
		entries, native, total := genFunc(&b, name, mem, uint32(a), uint32(a)+size)
		stats["native"] += native
		stats["total"] += total
		lo, hi := uint32(a), uint32(a)+size
		h := uint64(14695981039346656037) // FNV-1a, as cpu.CodeHash
		for _, x := range mem[lo:hi] {
			h = (h ^ uint64(x)) * 1099511628211
		}
		regs = append(regs, reg{name, entries, lo, hi, h})
	}
	fmt.Fprintf(&b, "func init() { registerAOT = registerAOTGenerated }\n\n// registerAOTGenerated installs the compiled functions (skipping addresses that already have an intercept,\n// and functions whose code in memory no longer matches what was compiled, e.g. after a patch).\nfunc registerAOTGenerated(c *cpu.CPU) {\n")
	for _, r := range regs {
		fmt.Fprintf(&b, "\tif c.CodeHash(%#x, %#x) != %#x {\n\t\tfmt.Printf(\"[c32aot] %s: code changed since compilation, not installed\\n\")\n\t} else {\n", r.lo, r.hi, r.codeHash, r.name)
		fmt.Fprintf(&b, "\tfor _, a := range []uint32{")
		for i, e := range r.entries {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "0x%08x", e)
		}
		fmt.Fprintf(&b, "} {\n\t\tif _, ok := c.Intercepts[a]; !ok {\n\t\t\tc.RegisterIntercept(a, %q, %s)\n\t\t}\n\t}\n\t}\n", "aot::"+r.name[4:], r.name)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "c32aot: generated code does not parse:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "c32aot: %d functions, %d/%d instructions native\n", len(regs), stats["native"], stats["total"])
}

func genFunc(b *strings.Builder, name string, mem []byte, start, end uint32) (entries []uint32, native, total int) {
	var insts []*inst
	for pc := start; pc < end; {
		in, err := x86asm.Decode(mem[pc:pc+16], 32)
		if err != nil || in.Len == 0 {
			break // data or undecodable: stop (the interpreter handles anything beyond)
		}
		it := &inst{pc: pc, in: in, next: pc + uint32(in.Len)}
		it.kind = classify(&in)
		insts = append(insts, it)
		pc = it.next
	}
	if len(insts) == 0 {
		return nil, 0, 0
	}
	inFunc := func(a uint32) bool { return a >= start && a < insts[len(insts)-1].next }
	leaders := map[uint32]bool{start: true}
	for i, it := range insts {
		switch it.kind {
		case kBranch, kJmp:
			if t := relTarget(it); inFunc(t) {
				leaders[t] = true
			}
			if i+1 < len(insts) {
				leaders[insts[i+1].pc] = true
			}
		case kRaw, kCall, kRet:
			if i+1 < len(insts) {
				leaders[insts[i+1].pc] = true // re-entry point after calls/returns/fallbacks
			}
		}
	}
	// Split into blocks.
	var blocks [][]*inst
	for _, it := range insts {
		if leaders[it.pc] || len(blocks) == 0 {
			blocks = append(blocks, nil)
		}
		blocks[len(blocks)-1] = append(blocks[len(blocks)-1], it)
	}
	// Leaders must be instruction starts; drop jump targets into the middle of an instruction.
	for _, blk := range blocks {
		entries = append(entries, blk[0].pc)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i] < entries[j] })

	fmt.Fprintf(b, "func %s(c *cpu.CPU) {\n\tc.Steps-- // the intercept dispatch counted one step; blocks count their own\n\tbudget := c.EventStep()\n\tswitch c.EIP {\n", name)
	for _, blk := range blocks {
		fmt.Fprintf(b, "\tcase 0x%08x:\n\t\tgoto L%08x\n", blk[0].pc, blk[0].pc)
	}
	b.WriteString("\tdefault:\n\t\tif c.Steps < budget {\n\t\t\tc.StepRaw()\n\t\t}\n\t\treturn\n\t}\n")
	for bi, blk := range blocks {
		liveness(blk)
		nat := 0
		for _, it := range blk {
			if it.kind != kRaw {
				nat++
			}
			if it.kind == kCall || it.kind == kRet {
				break // nothing after these runs in this block
			}
		}
		total += len(blk)
		native += nat
		fmt.Fprintf(b, "L%08x:\n", blk[0].pc)
		fmt.Fprintf(b, "\t\t\tif c.Steps+%d > budget {\n\t\t\t\tc.EIP = 0x%08x\n\t\t\t\tif c.Steps < budget {\n\t\t\t\t\tc.StepRaw()\n\t\t\t\t}\n\t\t\t\treturn\n\t\t\t}\n", len(blk), blk[0].pc)
		if nat > 0 {
			fmt.Fprintf(b, "\t\t\tc.Steps += %d\n", nat)
		}
		last := blk[len(blk)-1]
		for _, it := range blk {
			fmt.Fprintf(b, "\t\t\t// 0x%08x: %s\n", it.pc, x86asm.IntelSyntax(it.in, uint64(it.pc), nil))
			switch it.kind {
			case kNative:
				b.WriteString("\t\t\t{\n" + emitNative(it) + "\t\t\t}\n")
			case kRaw:
				fmt.Fprintf(b, "\t\t\tc.EIP = 0x%08x\n\t\t\tc.StepRaw()\n\t\t\tif c.EIP != 0x%08x || c.Halted {\n\t\t\t\treturn\n\t\t\t}\n", it.pc, it.next)
			case kBranch:
				t := relTarget(it)
				fmt.Fprintf(b, "\t\t\tif c.EvalCond(%d) {\n%s\t\t\t}\n", condCode(it.in.Op), gotoPC(t, inFunc(t), "\t\t\t\t"))
			case kJmp:
				t := relTarget(it)
				b.WriteString(gotoPC(t, inFunc(t), "\t\t\t"))
			case kCall: // as the interpreter: push, record the frame when tracing, jump
				t := relTarget(it)
				fmt.Fprintf(b, "\t\t\tc.Push32(0x%08x)\n", it.next)
				if t != it.next { // PIC "call $+5" is not recorded
					fmt.Fprintf(b, "\t\t\tif c.TraceCalls {\n\t\t\t\tc.CallStack = append(c.CallStack, cpu.CallFrame{CallerEIP: 0x%08x, TargetEIP: 0x%08x, ESP: c.Regs[4]})\n\t\t\t\tc.VisitedFuncs[0x%08x]++\n\t\t\t}\n", it.pc, t, t)
				}
				fmt.Fprintf(b, "\t\t\tc.EIP = 0x%08x\n\t\t\treturn\n", t)
			case kRet:
				b.WriteString("\t\t\tc.Ret()\n\t\t\treturn\n")
			}
		}
		if last.kind != kJmp && last.kind != kCall && last.kind != kRet {
			b.WriteString("\t\t\tif c.Halted {\n\t\t\t\treturn\n\t\t\t}\n")
			if bi+1 < len(blocks) && blocks[bi+1][0].pc == last.next {
				// falls through into the next block's label
			} else {
				b.WriteString(gotoPC(last.next, inFunc(last.next), "\t\t\t"))
			}
		}
	}
	b.WriteString("}\n\n")
	return entries, native, total
}

func gotoPC(t uint32, internal bool, ind string) string {
	if internal {
		return fmt.Sprintf("%sgoto L%08x\n", ind, t)
	}
	return fmt.Sprintf("%sc.EIP = 0x%08x\n%sreturn\n", ind, t, ind)
}

// nextFuncStart returns the first FDE or symbol address above a (or a+64K if there is none closer).
func nextFuncStart(img *macho32.Image, a uint32) uint32 {
	limit := a + 0x10000
	for f := range img.FDEs {
		if f > a && f < limit {
			limit = f
		}
	}
	for f := range img.SymbolsByAddr {
		if f > a && f < limit {
			limit = f
		}
	}
	return limit
}

// flowExtent returns the size of the code reachable from start through fall-through and direct
// branches/jumps (calls fall through; returns and indirect jumps end a path), staying below limit.
// Compiled blocks are exact entry points on their own, so an imprecise extent only changes how
// much is compiled, never what executes.
func flowExtent(mem []byte, start, limit uint32) uint32 {
	seen := map[uint32]bool{}
	work := []uint32{start}
	end := start
	for len(work) > 0 {
		pc := work[len(work)-1]
		work = work[:len(work)-1]
		for pc >= start && pc < limit && !seen[pc] {
			seen[pc] = true
			in, err := x86asm.Decode(mem[pc:pc+16], 32)
			if err != nil || in.Len == 0 {
				break
			}
			it := &inst{pc: pc, in: in, next: pc + uint32(in.Len)}
			end = max(end, it.next)
			switch classify(&in) {
			case kBranch:
				work = append(work, relTarget(it))
			case kJmp:
				work = append(work, relTarget(it))
				pc = 0 // path ends
				continue
			case kRet:
				pc = 0
				continue
			}
			if in.Op == x86asm.JMP || in.Op == x86asm.HLT || in.Op == x86asm.UD2 { // indirect jump
				break
			}
			pc = it.next
		}
	}
	return end - start
}

func relTarget(it *inst) uint32 {
	if r, ok := it.in.Args[0].(x86asm.Rel); ok {
		return uint32(int64(it.next) + int64(r))
	}
	return 0
}

var condOps = map[x86asm.Op]int{x86asm.JO: 0, x86asm.JNO: 1, x86asm.JB: 2, x86asm.JAE: 3, x86asm.JE: 4, x86asm.JNE: 5,
	x86asm.JBE: 6, x86asm.JA: 7, x86asm.JS: 8, x86asm.JNS: 9, x86asm.JP: 10, x86asm.JNP: 11, x86asm.JL: 12,
	x86asm.JGE: 13, x86asm.JLE: 14, x86asm.JG: 15}

var cmovOps = map[x86asm.Op]int{x86asm.CMOVO: 0, x86asm.CMOVNO: 1, x86asm.CMOVB: 2, x86asm.CMOVAE: 3, x86asm.CMOVE: 4,
	x86asm.CMOVNE: 5, x86asm.CMOVBE: 6, x86asm.CMOVA: 7, x86asm.CMOVS: 8, x86asm.CMOVNS: 9, x86asm.CMOVP: 10,
	x86asm.CMOVNP: 11, x86asm.CMOVL: 12, x86asm.CMOVGE: 13, x86asm.CMOVLE: 14, x86asm.CMOVG: 15}

func condCode(op x86asm.Op) int { return condOps[op] }

var aluOps = map[x86asm.Op]int{x86asm.ADD: 0, x86asm.OR: 1, x86asm.AND: 4, x86asm.SUB: 5, x86asm.XOR: 6, x86asm.CMP: 7}

func classify(in *x86asm.Inst) int {
	for _, p := range in.Prefix {
		if p == 0 {
			break
		}
		switch p &^ x86asm.PrefixImplicit &^ x86asm.PrefixIgnored {
		case x86asm.PrefixREP, x86asm.PrefixREPN:
			if !isScalarSSE(in.Op) {
				return kRaw
			}
		case x86asm.PrefixDataSize:
			if in.Op != x86asm.NOP && in.Op != x86asm.XORPD && in.Op != x86asm.MOVAPD && in.Op != x86asm.MOVUPD {
				return kRaw
			}
		case x86asm.PrefixCS, x86asm.PrefixDS, x86asm.PrefixES, x86asm.PrefixSS:
		case x86asm.PrefixFS, x86asm.PrefixGS, x86asm.PrefixLOCK, x86asm.PrefixAddrSize:
			return kRaw
		}
	}
	if _, ok := condOps[in.Op]; ok {
		if _, isRel := in.Args[0].(x86asm.Rel); isRel {
			return kBranch
		}
		return kRaw
	}
	if in.Op == x86asm.CALL {
		if _, isRel := in.Args[0].(x86asm.Rel); isRel {
			return kCall
		}
		return kRaw
	}
	if in.Op == x86asm.RET && in.Args[0] == nil {
		return kRet
	}
	if in.Op == x86asm.JMP {
		if _, isRel := in.Args[0].(x86asm.Rel); isRel {
			return kJmp
		}
		return kRaw
	}
	if emitNative(&inst{in: *in}) == "" {
		return kRaw
	}
	return kNative
}

func isScalarSSE(op x86asm.Op) bool {
	switch op {
	case x86asm.MOVSS, x86asm.ADDSS, x86asm.SUBSS, x86asm.MULSS, x86asm.DIVSS, x86asm.MAXSS, x86asm.MINSS,
		x86asm.MOVSD_XMM, x86asm.CVTSI2SS, x86asm.CVTTSS2SI:
		return true
	}
	return false
}

// liveness marks flag-setting instructions whose results are overwritten before being read
// within the block (flags are live at the end of every block).
func liveness(blk []*inst) {
	live := true
	for i := len(blk) - 1; i >= 0; i-- {
		it := blk[i]
		reads, writes := flagUse(it)
		if writes && !live {
			it.flagsDead = true
		}
		live = (live && !writes) || reads
	}
}

func flagUse(it *inst) (reads, writes bool) {
	op := it.in.Op
	if it.kind == kRaw || it.kind == kBranch {
		return true, false
	}
	if _, ok := cmovOps[op]; ok {
		return true, false
	}
	switch op {
	case x86asm.ADD, x86asm.SUB, x86asm.AND, x86asm.OR, x86asm.XOR, x86asm.CMP, x86asm.TEST, x86asm.UCOMISS, x86asm.COMISS:
		return false, true
	}
	return false, false
}

// ---- operand helpers -------------------------------------------------------------------------

var reg32 = map[x86asm.Reg]int{x86asm.EAX: 0, x86asm.ECX: 1, x86asm.EDX: 2, x86asm.EBX: 3, x86asm.ESP: 4, x86asm.EBP: 5, x86asm.ESI: 6, x86asm.EDI: 7}
var reg8 = map[x86asm.Reg]int{x86asm.AL: 0, x86asm.CL: 1, x86asm.DL: 2, x86asm.BL: 3, x86asm.AH: 4, x86asm.CH: 5, x86asm.DH: 6, x86asm.BH: 7}

func xmm(a x86asm.Arg) (int, bool) {
	r, ok := a.(x86asm.Reg)
	if !ok || r < x86asm.X0 || r > x86asm.X7 {
		return 0, false
	}
	return int(r - x86asm.X0), true
}

func ea(m x86asm.Mem) (string, bool) {
	if m.Segment != 0 && m.Segment != x86asm.DS && m.Segment != x86asm.SS && m.Segment != x86asm.ES && m.Segment != x86asm.CS {
		return "", false
	}
	var parts []string
	if m.Base != 0 {
		i, ok := reg32[m.Base]
		if !ok {
			return "", false
		}
		parts = append(parts, fmt.Sprintf("c.Regs[%d]", i))
	}
	if m.Index != 0 {
		i, ok := reg32[m.Index]
		if !ok {
			return "", false
		}
		sh := map[uint8]int{1: 0, 2: 1, 4: 2, 8: 3}[m.Scale]
		if sh == 0 {
			parts = append(parts, fmt.Sprintf("c.Regs[%d]", i))
		} else {
			parts = append(parts, fmt.Sprintf("c.Regs[%d]<<%d", i, sh))
		}
	}
	if m.Disp != 0 || len(parts) == 0 {
		parts = append(parts, fmt.Sprintf("0x%x", uint32(m.Disp)))
	}
	return "(" + strings.Join(parts, " + ") + ")", true
}

// src32 renders a 32-bit source operand; dst32 a store of expression v into a 32-bit operand.
func src32(in *x86asm.Inst, a x86asm.Arg) (string, bool) {
	switch a := a.(type) {
	case x86asm.Reg:
		i, ok := reg32[a]
		return fmt.Sprintf("c.Regs[%d]", i), ok
	case x86asm.Mem:
		if in.MemBytes != 4 {
			return "", false
		}
		e, ok := ea(a)
		return "c.Read32" + e, ok
	case x86asm.Imm:
		return fmt.Sprintf("uint32(0x%x)", uint32(a)), true
	}
	return "", false
}

func dst32(in *x86asm.Inst, a x86asm.Arg, v string) (string, bool) {
	switch a := a.(type) {
	case x86asm.Reg:
		i, ok := reg32[a]
		return fmt.Sprintf("c.Regs[%d] = %s", i, v), ok
	case x86asm.Mem:
		if in.MemBytes != 4 {
			return "", false
		}
		e, ok := ea(a)
		return fmt.Sprintf("c.Write32(%s, %s)", e, v), ok
	}
	return "", false
}

func src8(in *x86asm.Inst, a x86asm.Arg) (string, bool) {
	switch a := a.(type) {
	case x86asm.Reg:
		i, ok := reg8[a]
		return fmt.Sprintf("c.GetReg8(%d)", i), ok
	case x86asm.Mem:
		if in.MemBytes != 1 {
			return "", false
		}
		e, ok := ea(a)
		return "c.Read8" + e, ok
	case x86asm.Imm:
		return fmt.Sprintf("uint8(0x%x)", uint8(a)), true
	}
	return "", false
}

func dst8(in *x86asm.Inst, a x86asm.Arg, v string) (string, bool) {
	switch a := a.(type) {
	case x86asm.Reg:
		i, ok := reg8[a]
		return fmt.Sprintf("c.SetReg8(%d, %s)", i, v), ok
	case x86asm.Mem:
		if in.MemBytes != 1 {
			return "", false
		}
		e, ok := ea(a)
		return fmt.Sprintf("c.Write8(%s, %s)", e, v), ok
	}
	return "", false
}

func is8(a x86asm.Arg) bool {
	r, ok := a.(x86asm.Reg)
	_, is := reg8[r]
	return ok && is
}

// xmmSrcF32 renders a scalar float source: xmm lane 0 or a 32-bit memory operand.
func xmmSrcF32(in *x86asm.Inst, a x86asm.Arg) (string, bool) {
	if r, ok := xmm(a); ok {
		return fmt.Sprintf("c.XmmF32(%d)", r), true
	}
	if m, ok := a.(x86asm.Mem); ok && in.MemBytes == 4 {
		e, ok := ea(m)
		return "math.Float32frombits(c.Read32" + e + ")", ok
	}
	return "", false
}

// emitNative returns Go code for a natively translated instruction ("" = not translatable).
// Semantics mirror pkg/cpu (exec.go, fpu_sse.go, dcache.go) exactly.
func emitNative(it *inst) string {
	in := &it.in
	a0, a1, a2 := in.Args[0], in.Args[1], in.Args[2]
	line := func(format string, args ...any) string { return "\t\t\t" + fmt.Sprintf(format, args...) + "\n" }
	switch in.Op {
	case x86asm.NOP:
		return line("// nop")
	case x86asm.MOV:
		if is8(a0) || is8(a1) || in.MemBytes == 1 {
			if v, ok := src8(in, a1); ok {
				if s, ok := dst8(in, a0, v); ok {
					return line("%s", s)
				}
			}
			return ""
		}
		if v, ok := src32(in, a1); ok {
			if s, ok := dst32(in, a0, v); ok {
				return line("%s", s)
			}
		}
	case x86asm.MOVZX, x86asm.MOVSX:
		d, ok := reg32[asReg(a0)]
		if !ok {
			return ""
		}
		switch in.MemBytes {
		case 1, 0:
			if v, ok := src8(in, a1); ok {
				if in.Op == x86asm.MOVZX {
					return line("c.Regs[%d] = uint32(%s)", d, v)
				}
				return line("c.Regs[%d] = uint32(int32(int8(%s)))", d, v)
			}
		case 2:
			if m, ok := a1.(x86asm.Mem); ok {
				if e, ok := ea(m); ok {
					if in.Op == x86asm.MOVZX {
						return line("c.Regs[%d] = uint32(c.Read16%s)", d, e)
					}
					return line("c.Regs[%d] = uint32(int32(int16(c.Read16%s)))", d, e)
				}
			}
		}
	case x86asm.LEA:
		d, ok := reg32[asReg(a0)]
		m, isMem := a1.(x86asm.Mem)
		if ok && isMem {
			if e, ok := ea(m); ok {
				return line("c.Regs[%d] = %s", d, e)
			}
		}
	case x86asm.ADD, x86asm.SUB, x86asm.AND, x86asm.OR, x86asm.XOR, x86asm.CMP:
		op := aluOps[in.Op]
		if is8(a0) || is8(a1) || in.MemBytes == 1 {
			x, ok1 := src8(in, a0)
			y, ok2 := src8(in, a1)
			if !ok1 || !ok2 {
				return ""
			}
			st, ok := dst8(in, a0, "r")
			if !ok && in.Op != x86asm.CMP {
				return ""
			}
			if in.Op == x86asm.CMP {
				return line("c.AluOp8(%d, %s, %s)", op, x, y)
			}
			return line("if r, wb := c.AluOp8(%d, %s, %s); wb {\n\t\t\t\t%s\n\t\t\t}", op, x, y, st)
		}
		x, ok1 := src32(in, a0)
		y, ok2 := src32(in, a1)
		if !ok1 || !ok2 {
			return ""
		}
		_ = op
		if in.Op == x86asm.CMP {
			if it.flagsDead {
				return line("// flags dead")
			}
			return line("a, b := %s, %s\n\t\t\tc.UpdateFlagsSub32(a, b, a-b)", x, y)
		}
		if _, isMem := a0.(x86asm.Mem); isMem {
			e, _ := ea(a0.(x86asm.Mem))
			if it.flagsDead {
				return line("addr := %s\n\t\t\tc.Write32(addr, c.Read32(addr) %s %s)", e, goOp(in.Op), y)
			}
			return line("addr := %s\n\t\t\t%s\n\t\t\tc.Write32(addr, r)", e, aluFlags(in.Op, "c.Read32(addr)", y))
		}
		st, _ := dst32(in, a0, "r")
		if it.flagsDead {
			s, _ := dst32(in, a0, fmt.Sprintf("%s %s %s", x, goOp(in.Op), y))
			return line("%s", s)
		}
		return line("%s\n\t\t\t%s", aluFlags(in.Op, x, y), st)
	case x86asm.TEST:
		if it.flagsDead {
			return line("// flags dead")
		}
		if is8(a0) || is8(a1) || in.MemBytes == 1 {
			x, ok1 := src8(in, a0)
			y, ok2 := src8(in, a1)
			if ok1 && ok2 {
				return line("c.UpdateFlagsLogic8(%s & %s)", x, y)
			}
			return ""
		}
		x, ok1 := src32(in, a0)
		y, ok2 := src32(in, a1)
		if ok1 && ok2 {
			return line("c.UpdateFlagsLogic32(%s & %s)", x, y)
		}
	case x86asm.INC, x86asm.DEC:
		if is8(a0) || in.MemBytes == 1 || in.MemBytes == 2 {
			return ""
		}
		if _, ok := src32(in, a0); !ok {
			return ""
		}
		sign, upd := "+", "UpdateFlagsAdd32"
		if in.Op == x86asm.DEC {
			sign, upd = "-", "UpdateFlagsSub32"
		}
		if m, isMem := a0.(x86asm.Mem); isMem {
			e, _ := ea(m)
			return line("{\n\t\t\t\taddr := %s\n\t\t\t\tv := c.Read32(addr)\n\t\t\t\tcf := c.Flags & cpu.FlagCF\n\t\t\t\tc.%s(v, 1, v%s1)\n\t\t\t\tc.Flags = c.Flags&^cpu.FlagCF | cf\n\t\t\t\tc.Write32(addr, v%s1)\n\t\t\t}", e, upd, sign, sign)
		}
		d := reg32[asReg(a0)]
		return line("{\n\t\t\t\tv := c.Regs[%d]\n\t\t\t\tcf := c.Flags & cpu.FlagCF\n\t\t\t\tc.%s(v, 1, v%s1)\n\t\t\t\tc.Flags = c.Flags&^cpu.FlagCF | cf\n\t\t\t\tc.Regs[%d] = v%s1\n\t\t\t}", d, upd, sign, d, sign)
	case x86asm.PUSH:
		if in.DataSize != 32 {
			return ""
		}
		if v, ok := src32(in, a0); ok {
			return line("c.Push32(%s)", v)
		}
	case x86asm.POP:
		if d, ok := reg32[asReg(a0)]; ok {
			return line("c.Regs[%d] = c.Pop32()", d)
		}
	case x86asm.SHL, x86asm.SHR, x86asm.SAR:
		cnt, ok := a1.(x86asm.Imm)
		if !ok || in.MemBytes == 1 || is8(a0) {
			return ""
		}
		op := map[x86asm.Op]int{x86asm.SHL: 4, x86asm.SHR: 5, x86asm.SAR: 7}[in.Op]
		if r, isReg := a0.(x86asm.Reg); isReg {
			d, ok := reg32[r]
			if !ok {
				return ""
			}
			return line("c.Regs[%d] = c.ShiftOp32(%d, c.Regs[%d], %d)", d, op, d, uint8(cnt))
		}
		m, _ := a0.(x86asm.Mem)
		if e, ok := ea(m); ok && in.MemBytes == 4 {
			return line("{\n\t\t\t\taddr := %s\n\t\t\t\tc.Write32(addr, c.ShiftOp32(%d, c.Read32(addr), %d))\n\t\t\t}", e, op, uint8(cnt))
		}
	case x86asm.IMUL:
		if a2 == nil {
			return ""
		}
		d, ok := reg32[asReg(a0)]
		x, ok2 := src32(in, a1)
		imm, ok3 := a2.(x86asm.Imm)
		if ok && ok2 && ok3 {
			return line("{\n\t\t\t\tprod := int64(int32(%s)) * int64(%d)\n\t\t\t\tres := uint32(prod)\n\t\t\t\tc.Regs[%d] = res\n\t\t\t\tc.SetFlag(cpu.FlagCF|cpu.FlagOF, prod != int64(int32(res)))\n\t\t\t}", x, int32(imm), d)
		}
	case x86asm.MOVSS:
		if r, ok := xmm(a0); ok {
			if s, ok := xmm(a1); ok {
				return line("c.SetXmmF32(%d, c.XmmF32(%d))", r, s)
			}
			if m, ok := a1.(x86asm.Mem); ok {
				if e, ok := ea(m); ok {
					return line("{\n\t\t\t\tv := c.Read32%s\n\t\t\t\tc.XMM[%d] = [16]byte{}\n\t\t\t\tc.SetXmmF32(%d, math.Float32frombits(v))\n\t\t\t}", e, r, r)
				}
			}
			return ""
		}
		if s, ok := xmm(a1); ok {
			if m, ok := a0.(x86asm.Mem); ok {
				if e, ok := ea(m); ok {
					return line("c.Write32(%s, math.Float32bits(c.XmmF32(%d)))", e, s)
				}
			}
		}
	case x86asm.ADDSS, x86asm.SUBSS, x86asm.MULSS, x86asm.DIVSS:
		r, ok := xmm(a0)
		y, ok2 := xmmSrcF32(in, a1)
		if ok && ok2 {
			sym := map[x86asm.Op]string{x86asm.ADDSS: "+", x86asm.SUBSS: "-", x86asm.MULSS: "*", x86asm.DIVSS: "/"}[in.Op]
			// The explicit float32 rounds the result, so the Go compiler cannot fuse it into a
			// following add (arm64 FMA): every instruction rounds like SSE.
			return line("c.SetXmmF32(%d, float32(c.XmmF32(%d) %s %s))", r, r, sym, y)
		}
	case x86asm.MAXSS, x86asm.MINSS:
		r, ok := xmm(a0)
		y, ok2 := xmmSrcF32(in, a1)
		if ok && ok2 {
			cmp := ">"
			if in.Op == x86asm.MINSS {
				cmp = "<"
			}
			return line("{\n\t\t\t\ta, b := c.XmmF32(%d), %s\n\t\t\t\tif !(a %s b) {\n\t\t\t\t\ta = b\n\t\t\t\t}\n\t\t\t\tc.SetXmmF32(%d, a)\n\t\t\t}", r, y, cmp, r)
		}
	case x86asm.UCOMISS, x86asm.COMISS:
		if it.flagsDead {
			return line("// flags dead")
		}
		r, ok := xmm(a0)
		y, ok2 := xmmSrcF32(in, a1)
		if ok && ok2 {
			return line("c.CompareEFlags(float64(c.XmmF32(%d)), float64(%s))", r, y)
		}
	case x86asm.MOVAPS, x86asm.MOVUPS, x86asm.MOVAPD, x86asm.MOVUPD:
		if r, ok := xmm(a0); ok {
			if s, ok := xmm(a1); ok {
				return line("c.XMM[%d] = c.XMM[%d]", r, s)
			}
			if m, ok := a1.(x86asm.Mem); ok {
				if e, ok := ea(m); ok {
					return line("c.XMM[%d] = c.Read128(%s)", r, e)
				}
			}
			return ""
		}
		if s, ok := xmm(a1); ok {
			if m, ok := a0.(x86asm.Mem); ok {
				if e, ok := ea(m); ok {
					return line("c.Write128(%s, c.XMM[%d])", e, s)
				}
			}
		}
	case x86asm.XORPS, x86asm.XORPD:
		r, ok := xmm(a0)
		if s, ok2 := xmm(a1); ok && ok2 {
			return line("for i := range c.XMM[%d] {\n\t\t\t\tc.XMM[%d][i] ^= c.XMM[%d][i]\n\t\t\t}", r, r, s)
		}
	case x86asm.MOVSD_XMM:
		if r, ok := xmm(a0); ok {
			if m, ok := a1.(x86asm.Mem); ok {
				if e, ok := ea(m); ok {
					return line("{\n\t\t\t\tv := c.Read64%s\n\t\t\t\tc.XMM[%d] = [16]byte{}\n\t\t\t\tc.SetXmmF64(%d, math.Float64frombits(v))\n\t\t\t}", e, r, r)
				}
			}
			if s, ok := xmm(a1); ok {
				return line("c.SetXmmF64(%d, c.XmmF64(%d))", r, s)
			}
			return ""
		}
		if s, ok := xmm(a1); ok {
			if m, ok := a0.(x86asm.Mem); ok {
				if e, ok := ea(m); ok {
					return line("c.Write64(%s, math.Float64bits(c.XmmF64(%d)))", e, s)
				}
			}
		}
	case x86asm.CVTSI2SS:
		r, ok := xmm(a0)
		x, ok2 := src32(in, a1)
		if ok && ok2 {
			return line("c.SetXmmF32(%d, float32(int32(%s)))", r, x)
		}
	case x86asm.CVTTSS2SI:
		d, ok := reg32[asReg(a0)]
		y, ok2 := xmmSrcF32(in, a1)
		if ok && ok2 {
			return line("c.Regs[%d] = uint32(cpu.ToInt32(math.Trunc(float64(%s))))", d, y)
		}
	}
	if code, ok := cmovOps[in.Op]; ok {
		d, ok := reg32[asReg(a0)]
		x, ok2 := src32(in, a1)
		if ok && ok2 {
			return line("if v := %s; c.EvalCond(%d) {\n\t\t\t\tc.Regs[%d] = v\n\t\t\t}", x, code, d)
		}
	}
	return ""
}

// aluFlags computes r = x op y with the same flag updates as the interpreter's aluOp32.
func aluFlags(op x86asm.Op, x, y string) string {
	switch op {
	case x86asm.ADD:
		return fmt.Sprintf("a, b := %s, %s\n\t\t\tr := a + b\n\t\t\tc.UpdateFlagsAdd32(a, b, r)", x, y)
	case x86asm.SUB:
		return fmt.Sprintf("a, b := %s, %s\n\t\t\tr := a - b\n\t\t\tc.UpdateFlagsSub32(a, b, r)", x, y)
	}
	return fmt.Sprintf("r := %s %s %s\n\t\t\tc.UpdateFlagsLogic32(r)", x, goOp(op), y)
}

func asReg(a x86asm.Arg) x86asm.Reg {
	r, _ := a.(x86asm.Reg)
	return r
}

func goOp(op x86asm.Op) string {
	return map[x86asm.Op]string{x86asm.ADD: "+", x86asm.SUB: "-", x86asm.AND: "&", x86asm.OR: "|", x86asm.XOR: "^"}[op]
}
