// Command glgen writes the viewer's OpenGL stream decoder (viewer/C32GLCalls.h) from
// pkg/source's GLSpec. Run it through `go generate ./pkg/source`.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"catalina32/pkg/source"
)

func main() {
	out := filepath.Join("..", "..", "viewer", "C32GLCalls.h")
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	if err := os.WriteFile(out, Generate(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "glgen:", err)
		os.Exit(1)
	}
}

func ctype(a source.GLArg) string {
	switch a.Kind {
	case 'i':
		return "uint32_t"
	case 'l':
		return "intptr_t"
	case 'f':
		return "float"
	case 'd':
		return "double"
	case 's':
		return "const char *"
	case 'o':
		if a.Obj == 'H' {
			return "void *"
		}
		return "uint32_t"
	case 'g':
		return "uint32_t *"
	case 'x':
		return "const uint32_t *"
	}
	return "const void *" // '*', 'p'
}

func read(a source.GLArg, i int) string {
	switch a.Kind {
	case 'i':
		return "c32RdU(&p)"
	case 'l':
		return "(intptr_t)(int32_t)c32RdU(&p)"
	case 'f':
		return "c32RdF(&p)"
	case 'd':
		return "c32RdD(&p)"
	case 's':
		return "c32RdStr(&p)"
	case 'o':
		if a.Obj == 'H' {
			return "c32ObjH(d, c32RdU(&p))"
		}
		return fmt.Sprintf("c32Obj(d, '%c', c32RdU(&p))", a.Obj)
	case 'g':
		return fmt.Sprintf("c32GenNames(d, '%c', a%d, c32RdNames(&p, a%d), c32glFn[id])", a.Obj, i-1, i-1)
	case 'x':
		return fmt.Sprintf("c32DelNames(d, '%c', a%d, c32RdNames(&p, a%d))", a.Obj, i-1, i-1)
	case '*':
		return "c32RdBlob(&p)"
	}
	return "c32RdPixels(&p)" // 'p'
}

// Generate returns the decoder source.
func Generate() []byte {
	calls := source.ParseGLSpec()
	var b bytes.Buffer
	b.WriteString(`// Generated by cmd/glgen from pkg/source/glspec.go. DO NOT EDIT.
//
// The OpenGL stream's calls: names, ids and argument decoding. C32GL.m defines the readers
// (c32RdU, c32RdF, c32RdD, c32RdStr, c32RdBlob, c32RdPixels, c32RdNames), the object name maps
// (c32Obj, c32ObjH, c32GenNames, c32DelNames) and a handler c32gl_<name> for each call flagged V,
// then includes this file.

`)
	fmt.Fprintf(&b, "#define C32GL_VERSION %d\n#define C32GL_NCALLS %d\n\n", glVersion(), len(calls))
	b.WriteString("static const char *const c32glNames[C32GL_NCALLS] = {\n")
	for _, c := range calls {
		fmt.Fprintf(&b, "    \"%s\",\n", c.Name)
	}
	b.WriteString("};\n\nstatic void *c32glFn[C32GL_NCALLS];\n\n")
	for _, c := range calls {
		if !c.Viewer {
			continue
		}
		var params []string
		for i, a := range c.Args {
			params = append(params, fmt.Sprintf("%s a%d", ctype(a), i))
		}
		fmt.Fprintf(&b, "static void c32gl_%s(C32GLDecoder *d%s);\n", c.Name, prefixed(params))
	}
	b.WriteString(`
// c32glDecode runs call id with its arguments at p. It returns 0 for an unknown id.
static int c32glDecode(C32GLDecoder *d, uint32_t id, const uint8_t *p) {
    switch (id) {
`)
	for id, c := range calls {
		fmt.Fprintf(&b, "    case %d: { /* %s */\n", id, c.Name)
		var names, types []string
		for i, a := range c.Args {
			if a.Kind == 'g' { // created after the call's other arguments are read: the call itself
				continue
			}
			fmt.Fprintf(&b, "        %s a%d = %s;\n", ctype(a), i, read(a, i))
			names = append(names, fmt.Sprintf("a%d", i))
			types = append(types, ctype(a))
		}
		switch {
		case c.Viewer:
			fmt.Fprintf(&b, "        c32gl_%s(d%s);\n", c.Name, prefixed(names))
		case len(c.Args) > 0 && c.Args[len(c.Args)-1].Kind == 'g':
			g := c.Args[len(c.Args)-1]
			fmt.Fprintf(&b, "        %s;\n", read(g, len(c.Args)-1))
		default:
			if len(types) == 0 {
				types = []string{"void"}
			}
			fmt.Fprintf(&b, "        if (c32glFn[id]) ((void (*)(%s))c32glFn[id])(%s);\n", strings.Join(types, ", "), strings.Join(names, ", "))
		}
		b.WriteString("        return 1;\n    }\n")
	}
	b.WriteString("    }\n    return 0;\n}\n")
	return b.Bytes()
}

func prefixed(s []string) string {
	if len(s) == 0 {
		return ""
	}
	return ", " + strings.Join(s, ", ")
}

func glVersion() int { return source.GLVersion }
